/// <summary>
/// Ingress values supported by Azure Container Apps task inputs.
/// </summary>
public enum AzureContainerAppIngress
{
    /// <summary>
    /// Internet or VNET-reachable ingress.
    /// </summary>
    [YamlMember(Alias = "external")]
    External,

    /// <summary>
    /// Ingress reachable only from within the Container Apps environment.
    /// </summary>
    [YamlMember(Alias = "internal")]
    Internal,

    /// <summary>
    /// Disable ingress for the Container App.
    /// </summary>
    [YamlMember(Alias = "disabled")]
    Disabled,
}

/// <summary>
/// Optional kind values supported by Azure Container Apps task inputs.
/// </summary>
public enum AzureContainerAppKind
{
    /// <summary>
    /// Enables built-in support and autoscaling for Azure Functions on Container Apps.
    /// </summary>
    [YamlMember(Alias = "functionapp")]
    FunctionApp,
}
